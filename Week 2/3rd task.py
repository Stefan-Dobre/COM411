print("Towards which direction should I go (up, down, left, right?)")
direction = input()
if direction == "up":
    print("I am moving in upward direction")
elif direction == "left":
    print("I am moving in a leftward direction")
elif direction == "down":
    print("I am moving in downward direction")
elif direction == "right":
    print("I am moving in a rightward direction")
