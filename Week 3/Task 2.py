print("How many obstacles must I avoid?")
obstacle_avoided = int(input())
# control variable
obstacles_avoided = 0
print()
while obstacles_avoided < obstacle_avoided:
    print("Avoiding ...Done 1" ,end="")
    obstacles_avoided += 1
    print(f"done! {obstacles_avoided} obstacles avoided.")

